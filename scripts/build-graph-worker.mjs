#!/usr/bin/env node
/**
 * Bundle the graph layout worker (layout-worker-entry.ts, layout-core.ts and
 * force-layout.ts) into one script and write it as a string module:
 *
 *   editors/knowledge-vault/components/graph/layout-worker.generated.ts
 *
 * Why a string: the package's browser build (ph-cli → tsdown) does not emit
 * worker files, and Connect loads the package from wherever it is hosted. A
 * worker started from a Blob URL of this source works the same in Vetra, in
 * the published package and in any Connect, with no extra file to serve.
 *
 * Run after changing any of those three files; the test
 * `layout-worker.generated.test.ts` fails until you do.
 *
 *   bun run graph-worker      (node scripts/build-graph-worker.mjs)
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { rolldown } from "rolldown";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "editors/knowledge-vault/components/graph");
const sources = ["force-layout.ts", "layout-core.ts", "layout-worker-entry.ts"];

/** Must match sourceHash() in layout-worker.generated.test.ts. */
function sourceHash() {
  const h = createHash("sha256");
  for (const f of sources) h.update(readFileSync(join(dir, f), "utf8")).update("\0");
  return h.digest("hex").slice(0, 16);
}

const bundle = await rolldown({
  input: join(dir, "layout-worker-entry.ts"),
  platform: "browser",
  resolve: { extensionAlias: { ".js": [".ts", ".js"] } },
  logLevel: "warn",
});
const { output } = await bundle.generate({ format: "iife", minify: true });
await bundle.close();
const code = output[0].code;

const out = `// GENERATED by scripts/build-graph-worker.mjs from layout-worker-entry.ts,
// layout-core.ts and force-layout.ts. Do not edit; run \`node scripts/build-graph-worker.mjs\`.
/* oxlint-disable */

/** Hash of the sources this was built from; the test compares it. */
export const LAYOUT_WORKER_HASH = ${JSON.stringify(sourceHash())};

/** The layout worker as a classic script (an IIFE), started from a Blob URL. */
export const LAYOUT_WORKER_SOURCE = ${JSON.stringify(code)};
`;
writeFileSync(join(dir, "layout-worker.generated.ts"), out);
console.log(`layout-worker.generated.ts: ${(code.length / 1024).toFixed(1)} KiB, hash ${sourceHash()}`);
